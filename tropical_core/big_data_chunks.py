# Катастрофа бродкастинга (Векторизация против Памяти)
# Размер итоговой матрицы: Квадратная матрица 10 000 x 10 000 
# элементов типа float64 весит ровно 762.9 МБ. 
# Это совершенно нормально, она легко помещается в оперативную память любого ПК.
# Пиковый скрытый тензор: Но когда NumPy выполняет бродкастинг A[:, None, :] + B[None, :, :], 
# он на долю секунды создает в памяти промежуточный виртуальный 
# трехмерный тензор размера 10000 x 10000 x 10000.
# Объем просадки по памяти: Этот трехмерный гигант
#  требует \(10000^3 \times 8 \text{ байт} = 8 \text{ Терабайт}\) оперативной памяти!
#  Любой сервер мгновенно вылетит со смертельной 
# ошибкой MemoryError (Out of Memory).
# Вывод: Чистая векторизация через NumPy («Виктория») великолепно 
# работает на малых масштабах, но на больших массивах данных она полностью сжирает
#  всё дисковое пространство и память (Space).
# Как это правильно оптимизировать?
# Чтобы решить эту проблему и не тонуть в 
# потреблении памяти, мы должны использовать комбинированный подход — Numba JIT-компиляцию в Си-структуры.
# Она заменяет гигантские промежуточные тензоры на быстрые низкоуровневые указатели.

import numpy as np
from numba import njit, prange

@njit(parallel=True, fastmath=True)
def optimized_space_tropical_mul(A, B, zero_val):
    """
    Высокопроизводительное Си-ядро. 
    Оптимизирует Space Complexity (Пространственную сложность).
    НЕ создает промежуточных тензоров в памяти, решая проблему 8 Терабайт.
    """
    n = A.shape[0]
    m = B.shape[1]
    p = A.shape[1]
    
    # Итоговая матрица весит всего 762 МБ
    C = np.full((n, m), zero_val, dtype=np.float64)
    
    # Распараллеливаем вычисления по ядрам процессора без выделения лишней памяти
    for i in prange(n):
        for j in range(m):
            max_val = zero_val
            for k in range(p):
                if A[i, k] != zero_val and B[k, j] != zero_val:
                    current_val = A[i, k] + B[k, j]
                    if current_val > max_val:
                        max_val = current_val
            C[i, j] = max_val
            
    return C
