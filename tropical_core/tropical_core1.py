import numpy as np


class TropicalCore:
    """ЯДРО ТРОПИЧЕСКОЙ МАТЕМАТИКИ (TROPICAL CORE).

    Оцифрованная архитектура для max-plus и min-plus полуколец.
    Защищено от скрытых багов NumPy, NaN-значений и уплывания бесконечностей.
    """

    def __init__(self, mode="max"):
        """БЛОК 1. ИНИЦИАЛИЗАЦИЯ И ТРОПИЧЕСКИЙ НОЛЬ.

        МАТЕМАТИКА: В тропическом полукольце стандартный ноль не работает.
        Нейтральным элементом по сложению (пустотой) здесь является бесконечность.

        ЛОГИЧЕСКИЙ СМЫСЛ:
        - В 'max-plus' режиме мы ищем максимум, поэтому «пустота» — это минус
        бесконечность. Любое число больше неё.
        - В 'min-plus' режиме мы ищем минимум, поэтому «пустота» — это плюс
        бесконечность. Любое число меньше неё.
        """
        self.mode = mode.lower()
        if self.mode == "max":
            self.zero = float("-inf")  # Тропический ноль для max-plus
            self.one = 0.0  # Тропическая единица (нейтральный элемент умножения)
        elif self.mode == "min":
            self.zero = float("inf")  # Трапический ноль для min-plus
            self.one = 0.0
        else:
            raise ValueError(
                "Батенька, режим может быть только 'max' или 'min'!"
            )

    def add(self, a, b):
        """БЛОК 2. ТРОПИЧЕСКОЕ СЛОЖЕНИЕ (oplus).

        МАТЕМАТИКА: Сложение элементов заменяется операцией выбора экстремума.
        x ⊕ y = max(x, y)  или  min(x, y)

        ЧТО ОН ДАЁТ ЧЕЛОВЕКУ И УЧЁНЫМ:
        В экономике или логистике это инструмент мгновенной фильтрации. Если мы
        выбираем маршрут или оцениваем полезность товара (как в модели Болдуина),
        алгоритм не складывает затраты, а сразу отсекает худший вариант, оставляя
        только чистый максимум (или минимум) выгоды.
        """
        # Безопасное векторное сложение (работает и с числами, и с массивами NumPy)
        if self.mode == "max":
            return np.maximum(a, b)
        else:
            return np.minimum(a, b)

    def mul(self, a, b):
        """БЛОК 3. ТРОПИЧЕСКОЕ УМНОЖЕНИЕ (otimes).

        МАТЕМАТИКА: Умножение элементов заменяется обычным сложением!
        x ⊗ y = x + y

        ЧТО ОН ДАЁТ ЧЕЛОВЕКУ И УЧЁНЫМ:
        Это главный фокус тропической математики. Он превращает сложные
        нелинейные уравнения (например, степенные полиномы) в простые линейные
        графики. Компьютеру больше не нужно тратить ресурсы процессора на тяжелое
        перемножение матриц — он просто складывает числа в памяти. Это разгоняет
        алгоритмы в тысячи раз.

        СИСАДМИНСКАЯ ЗАЩИТА:
        Убран баг "if a == self.zero". Теперь метод использует векторный
        np.where. Если в массиве встречается тропический ноль (бесконечность),
        код гарантированно возвращает бесконечность, не вызывая падения
        амплитуды вычислений.
        """
        # Переводим в массивы NumPy для безопасной векторной работы
        a_arr = np.asarray(a, dtype=float)
        b_arr = np.asarray(b, dtype=float)

        # Проверяем, где в массивах сидят тропические нули (бесконечности)
        is_a_zero = np.isinf(a_arr) if self.mode == "max" else np.isinf(a_arr)
        is_b_zero = np.isinf(b_arr) if self.mode == "max" else np.isinf(b_arr)

        # Если складываем макс-плюс, то (-inf) + число должно быть (-inf).
        # np.where жестко контролирует, чтобы бесконечность поглощала операцию.
        result = np.where(is_a_zero | is_b_zero, self.zero, a_arr + b_arr)

        # Если на вход подавали обычные числа, возвращаем число, а не массив из 1 элемента
        if result.ndim == 0:
            return float(result)
        return result

    def build_tropical_matrix(self, standard_matrix):
        """БЛОК 4. КОНВЕРТЕР СТАНДАРТНОЙ МАТРИЦЫ В ТРОПИЧЕСКУЮ.

        МАТЕМАТИКА: Перевод обычной матрицы весов или цен в тропическое пространство.

        ЧТО ОН ДАЁТ ЧЕЛОВЕКУ И УЧЁНЫМ:
        В реальном мире (в архивах физики или таблицах цен) всегда есть хаос:
        пропуски данных (NaN) или отсутствие путей между точками (нули). Этот метод
        выгребает всю «многовековую пыль» из матрицы и переводит её на жесткий язык
        тропической логики.

        СИСАДМИНСКАЯ ЗАЩИТА (ВЫЧИЩЕНА ЛОВУШКА ДИАГОНАЛИ):
        - ВСЕ значения NaN (ошибки приборов, отсутствие данных) во всей матрице
          превращаются в честный тропический ноль (бесконечность).
        - Обычные нули преобразуются в бесконечность ТОЛЬКО вне главной диагонали.
          На главной диагонали (путь из вершины в саму себя) ноль остается нулем,
          потому что в тропической алгебре обычный 0 — это единица (нейтральный шаг).
        """
        matrix = np.array(standard_matrix, dtype=float)

        # 1. Зачищаем абсолютно все NaN в матрице — это слепые зоны, им место в бесконечности
        matrix[np.isnan(matrix)] = self.zero

        # 2. Поэлементно обрабатываем нули вне главной диагонали
        rows, cols = matrix.shape
        for i in range(rows):
            for j in range(cols):
                if i != j and matrix[i, j] == 0.0:
                    matrix[i, j] = self.zero

        return matrix

    def matmul(self, A, B):
        """БЛОК 5. ТРОПИЧЕСКОЕ УМНОЖЕНИЕ МАТРИЦ.

        МАТЕМАТИКА: Вместо строки на столбец (сумма произведений), мы делаем
        экстремум от сумм элементов!
        C[i,j] = max(A[i,k] + B[k,j])

        ЧТО ОН ДАЁТ ЧЕЛОВЕКУ И УЧЁНЫМ:
        Это чистый алгоритм Беллмана-Форда для поиска кратчайших путей в графах,
        записанный одной строчкой. Если матрица А — это дороги между городами,
        то возведение матрицы в тропическую степень мгновенно находит самые выгодные
        маршруты для транспорта или оленеводческих стад кочевников на долгой дистанции.
        """
        A = np.asarray(A, dtype=float)
        B = np.asarray(B, dtype=float)

        if A.shape[1] != B.shape[0]:
            raise ValueError(
                f"Матрицы не согласованы для умножения! {A.shape} и {B.shape}"
            )

        rows = A.shape[0]
        cols = B.shape[1]

        # Инициализируем результирующую матрицу чистыми тропическими нулями!
        result = np.full((rows, cols), self.zero)

        # Вычисляем тропическое произведение строк на столбцы
        for i in range(rows):
            for j in range(cols):
                # Для макс-плюс: max(A[i, :] + B[:, j])
                # Используем наши базовые методы add и mul в векторном формате
                row_col_sum = self.mul(A[i, :], B[:, j])
                if self.mode == "max":
                    result[i, j] = np.max(row_col_sum)
                else:
                    result[i, j] = np.min(row_col_sum)

        return result
